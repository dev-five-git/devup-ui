import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { describe, expect, it } from 'bun:test'

import {
  PrerenderArtifactError,
  verifyPrerender,
} from '../../apps/landing/verify-prerender'

const routes = ['/', '/nested/leaf'] as const
const artifacts = [
  ['/', 'index.html'],
  ['/', 'index.txt'],
  ['/nested/leaf', 'nested/leaf.html'],
  ['/nested/leaf', 'nested/leaf.txt'],
  ['/404', '404.html'],
] as const

function temporaryOutput() {
  const root = mkdtempSync(join(tmpdir(), 'landing-prerender-'))
  return {
    root,
    [Symbol.dispose]() {
      rmSync(root, { recursive: true, force: true })
    },
  }
}

function writeCompleteOutput(root: string): void {
  mkdirSync(join(root, 'nested'))
  // Independent fixture paths, not generated by Vinext or the verifier.
  writeFileSync(join(root, 'index.html'), '<html>home</html>')
  writeFileSync(join(root, 'index.txt'), 'home Flight')
  writeFileSync(join(root, 'nested/leaf.html'), '<html>leaf</html>')
  writeFileSync(join(root, 'nested/leaf.txt'), 'leaf Flight')
  writeFileSync(join(root, '404.html'), '<html>not found</html>')
}

it('accepts complete route pairs when the 404 has HTML only', () => {
  // Given
  using output = temporaryOutput()
  writeCompleteOutput(output.root)
  // When / Then
  expect(() => verifyPrerender(output.root, routes)).not.toThrow()
})

describe.each(artifacts)('route %s artifact %s', (route, artifact) => {
  it('rejects the artifact when it is missing', () => {
    // Given
    using output = temporaryOutput()
    writeCompleteOutput(output.root)
    const path = join(output.root, artifact)
    rmSync(path)
    // When / Then
    expect(() => verifyPrerender(output.root, routes)).toThrow(
      expect.objectContaining({
        constructor: PrerenderArtifactError,
        route,
        path,
        reason: 'missing',
      }),
    )
  })

  it('rejects the artifact when it is empty', () => {
    // Given
    using output = temporaryOutput()
    writeCompleteOutput(output.root)
    const path = join(output.root, artifact)
    writeFileSync(path, '')
    // When / Then
    expect(() => verifyPrerender(output.root, routes)).toThrow(
      expect.objectContaining({
        constructor: PrerenderArtifactError,
        route,
        path,
        reason: 'empty',
      }),
    )
  })

  it('rejects the artifact when it is a directory', () => {
    // Given
    using output = temporaryOutput()
    writeCompleteOutput(output.root)
    const path = join(output.root, artifact)
    rmSync(path)
    mkdirSync(path)
    // When / Then
    expect(() => verifyPrerender(output.root, routes)).toThrow(
      expect.objectContaining({
        constructor: PrerenderArtifactError,
        route,
        path,
        reason: 'not-file',
      }),
    )
  })
})

it('propagates native filesystem errors when the path contains a null byte', () => {
  // Given
  using output = temporaryOutput()
  const path = join(output.root, '\0')
  // When / Then
  expect(() => verifyPrerender(path, routes)).toThrow(
    expect.objectContaining({ code: 'ERR_INVALID_ARG_VALUE' }),
  )
})
