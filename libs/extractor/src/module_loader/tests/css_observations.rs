use serial_test::serial;

use super::super::retained_css::{CSS, ENTRY};
use crate::{ExtractOption, ExtractOutput, ResolvedModule};

fn extract_helper(helper: &str) -> Result<ExtractOutput, Box<dyn std::error::Error>> {
    let helper = helper.to_string();
    let resolver = move |specifier: &str, importer: &str| match (specifier, importer) {
        ("./helper", "/src/card.css.ts") => Some(ResolvedModule {
            path: "/src/helper.ts".to_string(),
            code: helper.clone(),
        }),
        ("./styles.module.css", "/src/helper.ts") => Some(ResolvedModule {
            path: "/src/styles.module.css".to_string(),
            code: CSS.to_string(),
        }),
        _ => None,
    };
    crate::extract_with_modules(
        "/src/card.css.ts",
        ENTRY,
        ExtractOption::default(),
        false,
        &resolver,
    )
}

