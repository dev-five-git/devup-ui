import { glob, readFile, writeFile } from 'node:fs/promises'

import { COMPONENT_GROUPS } from './src/constants/index.ts'

/** Explicit imports work in both Turbopack and Vite; no computed MDX imports. */
export async function generateI18n() {
  const pages = new Map([['/', 'src/app/HomePage.tsx']])
  for await (const file of glob('src/app/(detail)/**/page.{mdx,tsx}')) {
    const normalized = file.replaceAll('\\', '/')
    if (normalized.includes('[')) continue
    const path =
      normalized
        .replace('src/app/(detail)', '')
        .replace(/\/page\.(mdx|tsx)$/u, '') || '/'
    pages.set(path, normalized)
  }

  const translations = new Map()
  for await (const file of glob('src/content/ko/**/page.{mdx,tsx}')) {
    const normalized = file.replaceAll('\\', '/')
    const path =
      normalized
        .replace('src/content/ko', '')
        .replace(/\/page\.(mdx|tsx)$/u, '') || '/'
    if (!pages.has(path))
      throw new Error(`Translation has no English page: ${file}`)
    translations.set(path, normalized)
  }

  const components = Object.values(COMPONENT_GROUPS).flat()
  const componentTranslations = []
  for await (const file of glob(
    'src/content/ko/components/*/{index,Api}.mdx',
  )) {
    const normalized = file.replaceAll('\\', '/')
    if (!components.includes(normalized.split('/').at(-2))) {
      throw new Error(`Translation has no public English component: ${file}`)
    }
    componentTranslations.push(normalized)
  }

  const header = '// AUTO-GENERATED by apps/landing/script.js - do not edit.\n'
  const imports = (entries) =>
    [...entries]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(
        ([path, file]) =>
          `  '${path}': () => import('@/${file.slice(4).replace(/\.tsx$/u, '')}'),`,
      )
      .join('\n')

  await writeFile(
    'src/i18n/pages.generated.ts',
    `${header}import type { Metadata } from 'next'
import type { ComponentType } from 'react'

interface PageModule {
  default: ComponentType
  metadata?: Metadata
}

export const pages: Record<string, (() => Promise<PageModule>) | undefined> = {
${imports(pages)}
}

export const translations: Record<string, (() => Promise<PageModule>) | undefined> = {
${imports(translations)}
}
`,
  )

  const routes = [
    ...pages.keys(),
    ...components.map((component) => `/components/${component}`),
  ].sort()
  const translatedRoutes = [
    ...translations.keys(),
    ...components
      .filter((component) =>
        ['index', 'Api'].every((file) =>
          componentTranslations.includes(
            `src/content/ko/components/${component}/${file}.mdx`,
          ),
        ),
      )
      .map((component) => `/components/${component}`),
  ].sort()
  await writeFile(
    'src/i18n/routes.generated.ts',
    `${header}export const englishRoutes = ${JSON.stringify(routes, null, 2)} as const\nexport const translatedRoutes: readonly string[] = ${JSON.stringify(translatedRoutes, null, 2)}\n`,
  )

  await writeFile(
    'src/i18n/components.generated.ts',
    `${header}import type { MDXComponents } from 'mdx/types'
import type { ComponentType } from 'react'

export const componentTranslations: Record<string, (() => Promise<{ default: ComponentType<{ components?: MDXComponents }> }>) | undefined> = {
${imports(componentTranslations.map((file) => [file.replace('src/content/ko/', '').replace(/\.mdx$/u, ''), file]))}
}
`,
  )

  // Korean search replaces translated entries and retains English fallback entries.
  const search = JSON.parse(await readFile('public/search.json', 'utf8'))
  const translatedSearch = new Map()
  for (const [path, file] of translations) {
    const content = await readFile(file, 'utf8')
    const heading = /^#{1,6} (.+)$/mu.exec(content)
    if (heading)
      translatedSearch.set(path, {
        title: heading[1],
        text: content.slice(heading.index),
        url: `/ko${path === '/' ? '' : path}`,
      })
  }
  for (const component of new Set(
    componentTranslations.map((file) => file.split('/').at(-2)),
  )) {
    const path = `/components/${component}`
    const content = await Promise.all(
      ['index', 'Api'].map((name) => {
        const translatedFile = `src/content/ko/components/${component}/${name}.mdx`
        return readFile(
          componentTranslations.includes(translatedFile)
            ? translatedFile
            : `src/app/(detail)/components/[component]/${component}/${name}.mdx`,
          'utf8',
        )
      }),
    )
    translatedSearch.set(path, {
      title: component,
      text: content.join('\n'),
      url: `/ko${path}`,
    })
  }
  const koreanSearch = search.map((entry) => {
    const path = `/${entry.url.replace(/^\/|\/$/gu, '')}`
    return translatedSearch.get(path) ?? { ...entry, url: `/ko${path}` }
  })
  await writeFile('public/search.ko.json', JSON.stringify(koreanSearch))
}
