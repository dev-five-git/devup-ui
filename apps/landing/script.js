import { existsSync } from 'node:fs'
import { glob, readFile, writeFile } from 'node:fs/promises'

import { COMPONENT_GROUPS } from './src/constants/index.ts'

const files = await glob('src/app/(detail)/**/*.mdx')

const q = []
for await (const file of files) {
  if (file.endsWith('.ko.mdx')) continue
  q.push(
    readFile(file, {
      encoding: 'utf-8',
    }).then((content) => {
      const titleIndex = content.toString().indexOf('#')
      if (content.trim().length === 0 || titleIndex === -1) {
        return null
      }
      const normalized = file.replaceAll('\\', '/')
      const url = normalized
        .replace('src/app/(detail)', '')
        .replace('/[component]', '')
        .replace(/\/(?:page|index|Api|Description)\.mdx$/u, '')
      if (
        url.startsWith('/components/') &&
        url !== '/components/overview' &&
        !Object.values(COMPONENT_GROUPS).flat().includes(url.split('/').at(-1))
      )
        return null

      return {
        text: content.toString().substring(titleIndex),
        title: /(#)+ (.*)/.exec(content.toString())[2],
        url,
      }
    }),
  )
}

const res = (await Promise.all(q)).filter(Boolean)
const search = new Map()
for (const entry of res) {
  const previous = search.get(entry.url)
  search.set(
    entry.url,
    previous ? { ...previous, text: `${previous.text}\n${entry.text}` } : entry,
  )
}

await writeFile('public/search.json', JSON.stringify([...search.values()]))
// Korean files replace their English entry. A component page has two
// (index.ko.mdx and Api.ko.mdx), merged into one entry like the English ones.
const koreanEntries = new Map()
for await (const file of glob('src/app/(detail)/**/*.ko.mdx')) {
  const content = await readFile(file, 'utf8')
  const heading = /^#{1,6} (.+)$/mu.exec(content)
  if (!heading) continue
  const url = file
    .replaceAll('\\', '/')
    .replace('src/app/(detail)', '')
    .replace('/[component]', '')
    .replace(/\/(?:page|index|Api|Description)\.ko\.mdx$/u, '')
  const entry = { title: heading[1], text: content.slice(heading.index), url }
  const previous = koreanEntries.get(url)
  koreanEntries.set(
    url,
    previous ? { ...previous, text: `${previous.text}\n${entry.text}` } : entry,
  )
}
const koreanSearch = new Map([...search, ...koreanEntries])
await writeFile(
  'public/search.ko.json',
  JSON.stringify([...koreanSearch.values()]),
)

// Demo barrel.
//
// The component docs render every file under `<component>/demo/`. Discovering
// them at runtime (`readdir` + computed `import()`) or through a bundler
// specific helper (`import.meta.glob`) hides those edges from static import
// analysis, and only one of the two bundlers understands each form. Emitting
// explicit imports keeps the demo graph visible to BOTH Turbopack and Vite, so
// the Next and vinext builds extract styles from exactly the same file set.
const demoFiles = []
for await (const file of glob('src/app/**/demo/*.tsx')) {
  demoFiles.push(file.split(/[/\\]/).join('/'))
}

const demos = demoFiles
  .map((file) => {
    const segments = file.split('/')
    const filename = segments.at(-1)

    return {
      // `src/utils/demos.generated.ts` -> demo module, extension dropped so
      // both bundlers resolve it through their standard extension list.
      specifier: `../${segments.slice(1, -1).join('/')}/${filename.replace(/\.tsx$/, '')}`,
      // Label consumed by `getDemos`: `<component>/demo/<filename>`.
      label: `${segments.at(-3)}/demo/${filename}`,
    }
  })
  .sort((left, right) => left.specifier.localeCompare(right.specifier))

await writeFile(
  'src/utils/demos.generated.ts',
  [
    '// AUTO-GENERATED by apps/landing/script.js - do not edit by hand.',
    '// Run `node ./script.js` (part of `dev`, `build` and `build:next`) to refresh.',
    "import type { ComponentType } from 'react'",
    '',
    ...demos.map(
      ({ specifier }, index) => `import demo${index} from '${specifier}'`,
    ),
    '',
    'export const DEMOS: readonly (readonly [string, ComponentType])[] = [',
    ...demos.map(({ label }, index) => `  ['${label}', demo${index}],`),
    ']',
    '',
  ].join('\n'),
)

// Korean page registry.
//
// Every `page.ko.mdx` / `page.ko.tsx` under `src/app/(detail)` is a translated
// page: its URL is its directory with route groups and dynamic segments
// dropped, and it renders inside the `layout.tsx` files between `(detail)` and
// its directory, outermost first, as the English page does (the `(detail)`
// layout itself is the site shell, which `[locale]/layout.tsx` provides).
// Like the demo barrel, explicit imports keep the graph visible to both
// bundlers, so adding the file is all a translation needs.
const DETAIL_ROOT = 'src/app/(detail)'
const koreanPages = []
for await (const file of glob(`${DETAIL_ROOT}/**/page.ko.{mdx,tsx}`)) {
  const parts = file.split(/[/\\]/u)
  const filename = parts.at(-1)
  const segments = parts.slice(DETAIL_ROOT.split('/').length, -1)
  const layouts = segments
    .map((_, index) => segments.slice(0, index + 1).join('/'))
    .filter((dir) => existsSync(`${DETAIL_ROOT}/${dir}/layout.tsx`))
    .map((dir) => `@/app/(detail)/${dir}/layout`)
  koreanPages.push({
    url: `/${segments.filter((segment) => !/^[([]/u.test(segment)).join('/')}`,
    // MDX keeps its extension; TSX resolves through the standard extensions.
    specifier: [
      '@/app/(detail)',
      ...segments,
      filename.replace(/\.tsx$/u, ''),
    ].join('/'),
    layouts,
  })
}
koreanPages.sort((left, right) => left.url.localeCompare(right.url))
const layoutSpecifiers = [
  ...new Set(koreanPages.flatMap(({ layouts }) => layouts)),
].sort()

// Written in the repository's Prettier style so the file passes lint as is.
const loadLine = (specifier) => {
  const line = `    load: () => import('${specifier}'),`
  return line.length > 80
    ? `    load: () =>\n      import('${specifier}'),`
    : line
}
await writeFile(
  'src/i18n/pages.generated.ts',
  [
    '// AUTO-GENERATED by apps/landing/script.js - do not edit by hand.',
    '// Run `node ./script.js` (part of `dev`, `build` and `build:next`) to refresh.',
    ...layoutSpecifiers.map(
      (specifier, index) => `import layout${index} from '${specifier}'`,
    ),
    ...(layoutSpecifiers.length ? [''] : []),
    "import type { TranslatedPage } from './pages'",
    '',
    'export const TRANSLATED_PAGES: Readonly<Record<string, TranslatedPage>> = {',
    ...koreanPages.flatMap(({ url, specifier, layouts }) => [
      `  '${url}': {`,
      loadLine(specifier),
      `    layouts: [${layouts
        .map((layout) => `layout${layoutSpecifiers.indexOf(layout)}`)
        .join(', ')}],`,
      '  },',
    ]),
    '}',
    '',
  ].join('\n'),
)
